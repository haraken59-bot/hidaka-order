import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const source = readFileSync(new URL('../app.js', import.meta.url), 'utf8');
let saved, sent;
const window = { HidakaSupabase: { saveOrderHistory: async p => { sent = p; return { user_id: 'owner', saved_at: 'now' }; } } };
const context = vm.createContext({ window, console, localStorage: { setItem: (_, v) => { saved = JSON.parse(v); } } });
vm.runInContext(source.replace(/\n\s*boot\(\);\s*\n\}\)\(\);\s*$/, '\n globalThis.t = { defaultState, normalizeHistoryItem, applyHistoryEdit, historyEditTotal, sortedHistory, buildCloudOrderRecord, saveHistoryToCloud, planHistoryTransfer, deleteHistoryEntry, setState:s=>state=s };\n})();'), context);
const t = context.t, state = t.defaultState(); t.setState(state);
const h = t.normalizeHistoryItem({ id: 'h1', visitId: 'v1', date: '2026-10-07', items: [{ name: '串', category: 'skewer', unitPrice: 198, quantity: 5 }], proposedItems: [{ name: '串', category: 'skewer', unitPrice: 198, quantity: 5 }] });
state.history.push(h);
window.confirm = () => false;
await t.deleteHistoryEntry(h.id);
assert.equal(h.deletedAt, null, 'cancel deletion must leave history unchanged');
const edited = t.applyHistoryEdit(h, { items: [{ ...h.items[0], quantity: 3 }, { name: '追加', category: 'small', unitPrice: 100, quantity: 1, source: 'manual' }], satisfaction: '4', comment: '減らした' });
assert.equal(edited.total, 694);
assert.equal(edited.proposedItems[0].quantity, 5);
assert.equal(edited.removedItems[0].quantity, 2);
assert.equal(edited.feedback.satisfaction, 4);
assert.equal(h.items[0].quantity, 5, 'draft must not mutate original');
assert.equal(t.historyEditTotal([{ quantity: 1, unitPrice: null }]), null);
assert.throws(() => t.applyHistoryEdit(h, { items: [] }), /1品/);
assert.equal(t.historyEditTotal([{ quantity: -1, unitPrice: 1 }]), null);
state.history[0] = edited;
assert.equal((await t.saveHistoryToCloud(edited)).state, 'success');
assert.equal(sent.operation, 'edit');
assert.equal(sent.items.length, 2);
assert.equal(edited.cloudSave.pendingAction, undefined);
edited.deletedAt = '2026-10-08T00:00:00Z'; edited.cloudSave.pendingAction = 'delete';
window.HidakaSupabase.saveOrderHistory = async () => { throw Error('offline'); };
assert.equal((await t.saveHistoryToCloud(edited)).state, 'error');
assert.equal(saved.history[0].cloudSave.pendingAction, 'delete');
assert.equal(saved.history[0].cloudSave.ownerId, 'owner');
assert.equal(t.sortedHistory().length, 0);
assert.equal(t.normalizeHistoryItem(edited).deletedAt, edited.deletedAt);
assert.equal(t.normalizeHistoryItem(edited).removedItems[0].quantity, 2);
const empty = { user_id: 'owner', records: [] };
assert.equal(t.planHistoryTransfer([edited], empty, true).targets.length, 1);
assert.equal(t.planHistoryTransfer([edited], empty, false).targets.length, 0);
assert.equal(t.planHistoryTransfer([h], empty, false).targets.length, 1);
const known = { user_id: 'owner', records: [{ id: h.id, visit_id: h.visitId, deleted_at: null }] };
assert.equal(t.planHistoryTransfer([h], known, false).targets.length, 0);
known.records[0].deleted_at = 'now';
assert.equal(t.planHistoryTransfer([edited], known, true).targets.length, 0);
assert.throws(() => t.planHistoryTransfer([edited], { ...empty, user_id: 'other' }, true), /アカウント/);
assert.throws(() => t.planHistoryTransfer([h], { user_id: 'owner', records: [{ id: 'h1', visit_id: 'other' }] }, false), /対応/);
const legacy = t.normalizeHistoryItem({ id: 'old', date: '2020-01-01', items: ['不明な料理'] });
assert.equal(t.buildCloudOrderRecord(legacy).items[0].unit_price, null);
assert.equal(t.buildCloudOrderRecord(legacy).proposed_items, null);
const sql = readFileSync(new URL('../supabase/migrations/202610080001_history_management.sql',import.meta.url),'utf8');
assert.match(sql, /on conflict\s*\(user_id,order_history_id\) do nothing/);
assert.match(sql, /history is deleted/);
assert.doesNotMatch(sql, /(?:insert into|update|delete from|alter table) public\.(?:bottles|remaining_updates|store_visits|stores|brand_labels)\b/);
const read = readFileSync(new URL('../supabase/migrations/202610080002_history_management_read_context.sql',import.meta.url),'utf8');
assert.match(read, /history->>'deletedAt'/);
assert.equal((read.match(/tombstone.deleted_at is not null/g)||[]).length, 2);
console.log('History management: edits/totals/proposal preservation, tombstones, retry, owner/ID checks and legacy unknowns passed');
