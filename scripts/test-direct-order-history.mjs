import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const source = readFileSync(new URL('../app.js', import.meta.url), 'utf8');
let saved;
let cloudRecord;
const window = { HidakaSupabase: { saveOrderHistory: async record => { cloudRecord = record; return { user_id: 'owner', saved_at: '2026-10-01T00:00:00Z' }; } } };
const context = vm.createContext({ console, window, localStorage: { setItem: (k,v) => { saved = JSON.parse(v); } } });
vm.runInContext(source.replace(/\n\s*boot\(\);\s*\n\}\)\(\);\s*$/, '\n globalThis.test = { defaultState, createOrder, adjustOrderItem, createHistoryRecord, normalizeHistoryItem, normalizePendingOrder, buildCloudOrderRecord, saveHistoryToCloud, setState: s => { state = s; } };\n})();'), context);
const t = context.test;
const state = t.defaultState(); t.setState(state);
let order = t.createOrder({ ...state.preferences, drink: 'none' }, []);
order = t.adjustOrderItem(order, order.items.findIndex(i=>i.category==='skewer'));
order = t.adjustOrderItem(order, order.items.findIndex(i=>i.category==='skewer'));
order = t.normalizePendingOrder({ order }).order;
const manual = { ...state.menu.find(i=>i.category==='small'), manuallyAdded:true };
order.items.push(manual); order.total += manual.price;
const history = t.createHistoryRecord(order); state.history.push(history);
const cloud = t.buildCloudOrderRecord(history);
assert.equal(cloud.proposed_items.filter(i=>i.category==='skewer').length,5);
assert.equal(cloud.items.filter(i=>i.category==='skewer').length,3);
assert.equal(cloud.removed_items.length,2);
assert.equal(cloud.items.filter(i=>i.source==='manual').length,1);
assert.equal(cloud.starting_drink,null);
assert.equal(cloud.feedback,null);
assert.equal(cloud.items.reduce((s,i)=>s+i.unit_price*i.quantity,0),order.total);
assert.equal((await t.saveHistoryToCloud(history)).state,'success');
assert.equal(saved.history[0].cloudSave.ownerId,'owner');
const id=cloudRecord.id;
history.feedback = { satisfaction:5, comment:'よかった', updatedAt:'2026-10-01T01:00:00Z' };
await t.saveHistoryToCloud(history);
assert.equal(cloudRecord.id,id);
assert.equal(cloudRecord.feedback.satisfaction,5);
assert.equal(t.normalizeHistoryItem(history).proposedItems.length,history.proposedItems.length);
window.HidakaSupabase.saveOrderHistory = async () => { throw new Error('offline'); };
assert.equal((await t.saveHistoryToCloud(history)).state,'error');
assert.equal(saved.history[0].id,id);
assert.equal(saved.history[0].total,order.total);
assert.equal(saved.history[0].cloudSave.state,'failed');
assert.equal(saved.history[0].cloudSave.ownerId,'owner');
const sql = readFileSync(new URL('../supabase/migrations/202610010001_direct_order_history.sql',import.meta.url),'utf8');
assert.match(sql,/security invoker/);
assert.match(sql,/on conflict \(user_id,order_history_id\) do nothing/);
assert.doesNotMatch(sql,/(?:insert into|update|alter table) public\.(?:bottles|stores|store_visits|remaining_updates|brand_labels)\b/);
assert.ok(source.indexOf('state.history.push(historyRecord)') < source.indexOf('await saveHistoryToCloud(historyRecord)'));
console.log('Direct order snapshots, removal/manual distinctions, feedback and local fallback passed');
