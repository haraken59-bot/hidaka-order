import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const source = readFileSync(new URL('../app.js', import.meta.url), 'utf8');
const context = vm.createContext({ console });
vm.runInContext(source.replace(/\n\s*boot\(\);\s*\n\}\)\(\);\s*$/, '\n globalThis.test = { defaultState, createOrder, adjustOrderItem, createHistoryRecord, normalizeHistoryItem, normalizePendingOrder, orderHeading, setState: s => { state = s; } };\n})();'), context);
const t = context.test;
const state = t.defaultState();
t.setState(state);
const prefs = { ...state.preferences, drink: 'none' };
const initial = t.createOrder(prefs, []);
assert.equal(initial.items.filter(i => i.category === 'drink').length, 0);
assert.equal(initial.items.filter(i => i.category === 'skewer').length, 5);
let order = initial;
const shishito = order.items.findIndex(i => i.name.includes('ししとう'));
assert.ok(shishito >= 0);
order = t.adjustOrderItem(order, shishito);
order = t.adjustOrderItem(order, order.items.findIndex(i => i.category === 'skewer'));
assert.equal(order.items.filter(i => i.category === 'skewer').length, 3);
assert.equal(order.total, initial.total - order.removedItems.reduce((sum, e) => sum + e.item.price, 0));
assert.match(t.orderHeading(order), /串 3本/);
const pending = t.normalizePendingOrder({ order });
assert.equal(pending.order.removedItems.length, 2);
const history = t.createHistoryRecord(pending.order);
assert.equal(history.items.length, order.items.length);
assert.equal(history.total, order.total);
assert.equal(history.removedItems.length, 2);
assert.equal(t.normalizeHistoryItem(history).removedItems.length, 2);
assert.equal(history.context.startingDrinkId, '');
order = t.adjustOrderItem(pending.order, 1, true);
order = t.adjustOrderItem(order, 0, true);
assert.equal(order.total, initial.total);
assert.equal(order.items.length, initial.items.length);
for (const category of ['small', 'skewer', 'main', 'drink']) {
  const item = { id: `test-${category}`, name: category, price: 123, category, tags: [], actual: true };
  const augmented = { ...initial, items: [...initial.items, item], total: initial.total + 123 };
  const reduced = t.adjustOrderItem(augmented, augmented.items.length - 1);
  assert.equal(reduced.total, initial.total);
  assert.equal(t.adjustOrderItem(reduced, 0, true).total, augmented.total);
}
const drinkOrder = t.createOrder({ ...prefs, drink: 'highball' }, []);
const withoutDrink = t.adjustOrderItem(drinkOrder, drinkOrder.items.findIndex(i => i.category === 'drink'));
assert.equal(t.createHistoryRecord(withoutDrink).context.startingDrinkId, '');
const manual = { ...initial.items[0], manuallyAdded: true };
const withManual = { ...order, items: [...order.items, manual], total: order.total + manual.price };
const adjusted = t.adjustOrderItem(withManual, 0);
assert.equal(adjusted.items.at(-1).manuallyAdded, true);
assert.equal(t.createHistoryRecord(adjusted).items.at(-1).source, 'manual');
assert.equal(initial.items.length, t.createOrder(prefs, []).items.length);
console.log('Order reduction tests passed');
